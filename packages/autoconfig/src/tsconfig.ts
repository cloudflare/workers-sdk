import { existsSync, readFileSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { parseJSONC } from "@cloudflare/workers-utils";
import { applyEdits, modify } from "jsonc-parser";
import type { AutoConfigContext } from "./context";

/** Where `cf workers types` generates the Worker's types, as included by `cf init` */
export const CLOUDFLARE_TYPES_INCLUDE = ".cloudflare/types";

/** jsonc-parser can't parse a UTF-8 byte order mark, so it is set aside while editing */
const BOM = "\uFEFF";

/** A change to the project's `tsconfig.json` so that it includes the cf-generated types */
export type CloudflareTypesTsconfigUpdate =
	| { type: "update"; path: string; content: string }
	| { type: "manual"; message: string };

/**
 * Builds the message asking the user to add the cf-generated types to `tsconfig.json`.
 *
 * @param hasInclude Whether `tsconfig.json` has its own `include` array
 * @returns The message to show the user
 */
function getManualUpdateMessage(hasInclude: boolean): string {
	const reason =
		"so that TypeScript can find the types that `cf workers types` generates";
	return hasInclude
		? `Add ${JSON.stringify(CLOUDFLARE_TYPES_INCLUDE)} to the \`include\` array in tsconfig.json ${reason}.`
		: `Add an \`include\` array to tsconfig.json that keeps the files it includes today and adds ${JSON.stringify(CLOUDFLARE_TYPES_INCLUDE)}, for example ${JSON.stringify(["**/*", CLOUDFLARE_TYPES_INCLUDE])}, ${reason}.`;
}

/**
 * Checks whether an `include` entry already covers the cf-generated types.
 *
 * @param entry An entry of the `include` array
 * @returns Whether the entry includes `.cloudflare/types`
 */
function includesCloudflareTypes(entry: unknown): boolean {
	if (typeof entry !== "string") {
		return false;
	}
	const path = entry.replace(/^\.\//, "").replace(/\/$/, "");
	return (
		path === ".cloudflare" ||
		path === CLOUDFLARE_TYPES_INCLUDE ||
		path.startsWith(`${CLOUDFLARE_TYPES_INCLUDE}/`) ||
		path.startsWith(".cloudflare/**")
	);
}

/**
 * Works out how to add the types generated by `cf workers types` to the project's
 * `tsconfig.json`. `include` patterns such as `**\/*` skip dot-directories, so
 * `.cloudflare/types` needs its own `include` entry.
 *
 * @param projectPath The project directory
 * @returns The updated `tsconfig.json`, a message when it has to be updated by hand,
 *   or `undefined` when there is no `tsconfig.json` or it already includes the types
 */
export function getCloudflareTypesTsconfigUpdate(
	projectPath: string
): CloudflareTypesTsconfigUpdate | undefined {
	const tsconfigPath = join(projectPath, "tsconfig.json");
	if (!existsSync(tsconfigPath)) {
		return undefined;
	}

	let hasBom: boolean;
	let json: string;
	let include: unknown;
	try {
		const content = readFileSync(tsconfigPath, "utf8");
		hasBom = content.startsWith(BOM);
		json = hasBom ? content.slice(BOM.length) : content;
		({ include } = parseJSONC(json, tsconfigPath) as { include?: unknown });
	} catch {
		return { type: "manual", message: getManualUpdateMessage(true) };
	}
	// Without an `include` array, adding one would replace the default or inherited includes
	if (!Array.isArray(include)) {
		return { type: "manual", message: getManualUpdateMessage(false) };
	}
	if (include.some(includesCloudflareTypes)) {
		return undefined;
	}

	const indentation = /^([ \t]+)"include"/m.exec(json)?.[1] ?? "\t";
	const edits = modify(json, ["include", -1], CLOUDFLARE_TYPES_INCLUDE, {
		isArrayInsertion: true,
		formattingOptions: {
			insertSpaces: !indentation.startsWith("\t"),
			tabSize: indentation.startsWith("\t") ? 1 : indentation.length,
		},
	});
	return {
		type: "update",
		path: tsconfigPath,
		content: (hasBom ? BOM : "") + applyEdits(json, edits),
	};
}

/**
 * Adds the types generated by `cf workers types` to the project's `tsconfig.json`.
 * Failing to update it shouldn't stop autoconfig, so errors fall back to a message.
 *
 * @param projectPath The project directory
 * @param context The autoconfig context providing the logger
 */
export async function saveCloudflareTypesTsconfigUpdate(
	projectPath: string,
	context: AutoConfigContext
): Promise<void> {
	const update = getCloudflareTypesTsconfigUpdate(projectPath);
	if (update?.type !== "update") {
		return;
	}
	try {
		await writeFile(update.path, update.content);
	} catch {
		context.logger.warn(getManualUpdateMessage(true));
	}
}
