import { dedent } from "ts-dedent";
import type { ParsedWorkerConfig } from "./schema";

interface WorkerModulesOptions {
	/**
	 * Name of the Worker defined in `configPath`. Its module is typed from the
	 * config file, like the global `Env`.
	 */
	configWorkerName?: string;
	/** Other Workers in the project, typed from their parsed config. */
	otherWorkers?: Pick<ParsedWorkerConfig, "name" | "env">[];
}

interface GenerateTypesOptions {
	/** Path to the config file (relative to the generated `.d.ts`). */
	configPath: string;
	/**
	 * Package name used in the inline `import("<packageName>")` type expressions
	 * for `InferEnv`/`InferDurableNamespaces`/`InferMainModule`/`UnwrapConfig`.
	 *
	 * Defaults to `"@cloudflare/config"`. Integrations should pass the public
	 * `cf/config` package used to author `cloudflare.config.ts` files.
	 */
	packageName?: string;
	/**
	 * Experimental: declare a `cloudflare:workers/<name>` module for each Worker,
	 * whose `env`, `WorkerEntrypoint` and `DurableObject` use that Worker's `env`
	 * instead of the global `Env`. The bundler must resolve these modules to
	 * `cloudflare:workers`.
	 */
	workerModules?: WorkerModulesOptions;
}

/**
 * Generate the content for a Worker types declaration file.
 *
 * @example
 * ```typescript
 * import { generateTypes } from "@cloudflare/config";
 * import { writeFileSync } from "node:fs";
 *
 * const content = generateTypes({
 *   configPath: "../../cloudflare.config.ts",
 * });
 *
 * writeFileSync(".cloudflare/types/index.d.ts", content);
 * ```
 */
export function generateTypes({
	configPath,
	packageName = "@cloudflare/config",
	workerModules,
}: GenerateTypesOptions): string {
	// Strip .ts/.js extension for import path
	const configImportPath = configPath.replace(/\.(ts|js|mts|mjs)$/, "");

	const workerModuleDeclarations = [
		...(workerModules?.configWorkerName !== undefined
			? [generateWorkerModule(workerModules.configWorkerName, "__Env")]
			: []),
		// Other Workers have no config file to import, so their parsed `env` is
		// written as a type literal for `InferEnv` to read.
		...(workerModules?.otherWorkers ?? []).map((worker) =>
			generateWorkerModule(
				worker.name,
				`import("${packageName}").InferEnv<{ env: ${JSON.stringify(worker.env ?? {})} }>`
			)
		),
	];

	return (
		dedent`
		/* eslint-disable */
		// Generated by @cloudflare/config
		type __Config = import("${packageName}").UnwrapConfig<typeof import("${configImportPath}").default>;
		type __WorkerConfig = import("${packageName}").UnwrapConfig<__Config["worker"]>;
		type __Env = import("${packageName}").InferEnv<__WorkerConfig>;

		declare namespace Cloudflare {
			interface GlobalProps {
				mainModule: import("${packageName}").InferMainModule<__WorkerConfig>;
				durableNamespaces: import("${packageName}").InferDurableNamespaces<__WorkerConfig>;
			}
			interface Env extends __Env {}
		}
		interface Env extends Cloudflare.Env {}

	` + workerModuleDeclarations.map((declaration) => `\n${declaration}`).join("")
	);
}

/**
 * Generate the `cloudflare:workers/<name>` module declaration for one Worker.
 *
 * Only the exports whose types read the global `Env` are redeclared. Everything
 * else is still imported from `cloudflare:workers`.
 *
 * @param name The Worker's name.
 * @param envType A type expression for the Worker's `env`.
 * @returns The module declaration.
 */
function generateWorkerModule(name: string, envType: string): string {
	return dedent`
		declare module ${JSON.stringify(`cloudflare:workers/${name}`)} {
			// Keeps the helper type below from being exported
			export {};
			type __WorkerEnv = ${envType};
			export const env: __WorkerEnv;
			export abstract class WorkerEntrypoint<Env = __WorkerEnv, Props = {}> extends CloudflareWorkersModule.WorkerEntrypoint<Env, Props> {}
			export abstract class DurableObject<Env = __WorkerEnv, Props = {}> extends CloudflareWorkersModule.DurableObject<Env, Props> {}
		}
	`;
}
